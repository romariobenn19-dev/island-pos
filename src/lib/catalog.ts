// No prices or barcodes: those differ by shop and are added by the owner
// (or picked up when a barcode is scanned for the first time).
// Pack size = units per case/pack when buying from the wholesaler (typical, editable).

export interface CatalogItem {
  name: string
  category: string
  aliases?: string[]
  packSize?: number
  packName?: string
  unit?: string
}

const c = (category: string, items: (string | [string, Partial<CatalogItem>])[]): CatalogItem[] =>
  items.map((it) => (typeof it === 'string' ? { name: it, category } : { name: it[0], category, ...it[1] }))

