// Starter list of items commonly sold in Barbados shops, minimarts, rum shops and snackettes.
// No prices or barcodes: those differ by shop and are added by the owner (or picked up when a
// barcode is scanned for the first time). Pack size = units per case/pack when buying from the
// wholesaler (typical values, editable per item). Brand names are only ones widely sold in
// Barbados; anything else is a generic item the owner can rename.

export interface CatalogItem {
  name: string
  category: string
  aliases?: string[]
  packSize?: number
  packName?: string
  unit?: string
}

type Opts = Partial<Omit<CatalogItem, 'name' | 'category'>>
type Entry = string | [string, Opts]

const group = (category: string, items: Entry[]): CatalogItem[] =>
  items.map((it) => (typeof it === 'string' ? { name: it, category } : { name: it[0], category, ...it[1] }))

/** One item per size: sizes('Coca-Cola', ['20oz', '2L'], {...}) -> "Coca-Cola 20oz", "Coca-Cola 2L". */
const sizes = (name: string, list: [string, Opts?][], base: Opts = {}): Entry[] =>
  list.map(([size, o]) => [`${name} ${size}`, { ...base, ...o, aliases: [...(base.aliases ?? []), ...(o?.aliases ?? [])] }])

const per = (n: number, packName = 'case'): Opts => ({ packSize: n, packName })
const lb: Opts = { unit: 'lb' }

